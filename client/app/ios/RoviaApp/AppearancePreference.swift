import SwiftUI

/// The app's own appearance choice. The extension has no UI, so this is the
/// app process's business only — persisted in user defaults, applied at the
/// window root, and never written into the tunnel hand-off.
enum AppearancePreference: String, CaseIterable, Identifiable, Sendable {
    case system
    case light
    case dark

    var id: String { rawValue }

    var title: String {
        switch self {
        case .system: "System"
        case .light: "Light"
        case .dark: "Dark"
        }
    }

    var colorScheme: ColorScheme? {
        switch self {
        case .system: nil
        case .light: .light
        case .dark: .dark
        }
    }
}
